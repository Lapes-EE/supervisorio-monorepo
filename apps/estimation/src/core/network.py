R = R_ohms / Zbase
X = X_ohms / Zbase


def montar_ybus():
    Y = np.zeros_like(R, dtype=complex)

    for i in range(R.shape[0]):
        for j in range(R.shape[1]):
            if i != j and (R[i, j] != 0 or X[i, j] != 0):
                Y[i, j] = -1 / (R[i, j] + 1j * X[i, j])

    for i in range(R.shape[0]):
        Y[i, i] = -np.sum(Y[i, :])

    return Y


def obter_linhas(Y):
    linhas = []
    n = Y.shape[0]

    for i in range(n):
        for j in range(i + 1, n):
            if abs(Y[i, j]) > 0:
                linhas.append((i, j))

    return linhas


def criar_rede():
    Y = montar_ybus()
    linhas = obter_linhas(Y)
    return Y, linhas