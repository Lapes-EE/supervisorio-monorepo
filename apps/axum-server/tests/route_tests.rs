#[tokio::test]
async fn test_authenticated_route_access_avoids_db_select_and_hashing() {
    // THIS TEST VALIDATES THAT AUTHENTICATED ROUTES BYPASS DB SELECT AND ARGON2 HASHING
    // BY USING THE FACTORY PATTERN FOR TOKEN GENERATION.
    let factory = TestAppFactory::new();
    let app = factory.create_router();

    let start_time = Instant::now();

    // 1. Generate authentication token via Factory Pattern.
    // Notice: 0 SQL queries executed against "user" table, 0 Argon2 password hash verifications.
    let token = factory.auth_factory.create_token("user-id-12345");
    assert!(!token.is_empty(), "Factory token must not be empty");

    // 2. Dispatch request to authenticated route POST /meters
    let payload = json!({
        "name": "", // Empty name to trigger handler payload validation AFTER AuthUser extractor passes
        "ip": "192.168.1.100",
        "issoSerial": "258-A17-39C-D6A",
        "description": "Test Meter"
    });

    let req = Request::builder()
        .method("POST")
        .uri("/meters")
        .header(http::header::AUTHORIZATION, format!("Bearer {}", token))
        .header(http::header::CONTENT_TYPE, "application/json")
        .body(Body::from(payload.to_string()))
        .unwrap();

    let response = app.oneshot(req).await.unwrap();
    let duration = start_time.elapsed();

    // 3. Assertions confirming authentication passed WITHOUT 401 Unauthorized:
    // Status is 400 Bad Request because handler's payload validation ran.
    // If auth failed, status would be 401 Unauthorized.
    assert_ne!(
        response.status(),
        StatusCode::UNAUTHORIZED,
        "Authentication should pass using factory token without 401 Unauthorized"
    );
    assert_eq!(
        response.status(),
        StatusCode::BAD_REQUEST,
        "Auth pass confirmed; payload validation error returned"
    );

    let json_res = response_to_json(response).await;
    assert_eq!(json_res, json!({ "error": "Meter name is required" }));

    // Factory token creation + auth extraction completed rapidly without Argon2 hashing or DB SELECT queries
    println!(
        "Factory authentication test completed in {:?} (DB SELECT and Argon2 hashing avoided)",
        duration
    );
}

#[tokio::test]
async fn test_create_meter_auth_validation() {
    let factory = TestAppFactory::new();

    // Case 1: Unauthenticated (No Auth Header) -> 401 Unauthorized
    {
        let app = factory.create_router();
        let req = factory.unauthenticated_request(
            http::Method::POST,
            "/meters",
            Some(json!({
                "name": "Meter 1",
                "ip": "192.168.1.1",
                "issoSerial": "258-A17-39C-D6A",
                "description": "Desc"
            })),
        );
        let response = app.oneshot(req).await.unwrap();
        assert_eq!(response.status(), StatusCode::UNAUTHORIZED);
    }

    // Case 2: Invalid Token -> 401 Unauthorized
    {
        let app = factory.create_router();
        let req = Request::builder()
            .method("POST")
            .uri("/meters")
            .header(http::header::AUTHORIZATION, "Bearer invalid.jwt.token")
            .header(http::header::CONTENT_TYPE, "application/json")
            .body(Body::from(json!({}).to_string()))
            .unwrap();
        let response = app.oneshot(req).await.unwrap();
        assert_eq!(response.status(), StatusCode::UNAUTHORIZED);
    }

    // Case 3: Valid Factory Auth Token + Empty Name -> 400 Bad Request
    {
        let app = factory.create_router();
        let req = factory.authenticated_request(
            http::Method::POST,
            "/meters",
            "test_user",
            Some(json!({
                "name": "   ",
                "ip": "192.168.1.1",
                "issoSerial": "258-A17-39C-D6A",
                "description": "Desc"
            })),
        );
        let response = app.oneshot(req).await.unwrap();
        assert_eq!(response.status(), StatusCode::BAD_REQUEST);
        let json_res = response_to_json(response).await;
        assert_eq!(json_res, json!({ "error": "Meter name is required" }));
    }

    // Case 4: Valid Factory Auth Token + Invalid IP -> 400 Bad Request
    {
        let app = factory.create_router();
        let req = factory.authenticated_request(
            http::Method::POST,
            "/meters",
            "test_user",
            Some(json!({
                "name": "Valid Meter",
                "ip": "invalid_ip_format",
                "issoSerial": "258-A17-39C-D6A",
                "description": "Desc"
            })),
        );
        let response = app.oneshot(req).await.unwrap();
        assert_eq!(response.status(), StatusCode::BAD_REQUEST);
        let json_res = response_to_json(response).await;
        assert_eq!(json_res, json!({ "error": "IP inválido" }));
    }

    // Case 5: Valid Factory Auth Token + Invalid Serial -> 400 Bad Request
    {
        let app = factory.create_router();
        let req = factory.authenticated_request(
            http::Method::POST,
            "/meters",
            "test_user",
            Some(json!({
                "name": "Valid Meter",
                "ip": "192.168.1.1",
                "issoSerial": "INVALID-SERIAL",
                "description": "Desc"
            })),
        );
        let response = app.oneshot(req).await.unwrap();
        assert_eq!(response.status(), StatusCode::BAD_REQUEST);
        let json_res = response_to_json(response).await;
        assert_eq!(
            json_res,
            json!({ "error": "Serial inválido. Formato esperado: 258-A17-39C-D6A" })
        );
    }
}

