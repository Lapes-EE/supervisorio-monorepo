use axum::{
    body::Body,
    http::{self, Request, StatusCode},
};
use axum_server::{AppState, create_app};
use http_body_util::BodyExt;
use serde_json::{Value, json};
use std::time::Instant;
use tower::ServiceExt;

/// Factory pattern for creating authentication tokens directly in memory for test scenarios.
/// This pattern avoids executing database `SELECT` queries on the user table and CPU-bound Argon2 password hashing.
pub struct AuthTokenFactory {
    jwt_secret: String,
}

impl AuthTokenFactory {
    pub fn new(jwt_secret: impl Into<String>) -> Self {
        Self {
            jwt_secret: jwt_secret.into(),
        }
    }

    /// Mint a signed JWT token directly using the secret key in memory.
    ///
    /// # Avoided Operations:
    /// - Database SELECT query on user credentials
    /// - Argon2 CPU-expensive password hashing
    pub fn create_token(&self, user_id: &str) -> String {
        axum_server::auth::create_jwt(user_id, &self.jwt_secret)
            .expect("Factory should successfully create valid JWT token")
    }

    /// Create an `Authorization: Bearer <token>` header value.
    pub fn bearer_header(&self, user_id: &str) -> String {
        format!("Bearer {}", self.create_token(user_id))
    }
}

/// Test application factory providing configured Axum router and auth factory.
pub struct TestAppFactory {
    pub jwt_secret: String,
    pub auth_factory: AuthTokenFactory,
}

impl TestAppFactory {
    pub fn new() -> Self {
        let jwt_secret = "test_jwt_secret_key_987654321".to_string();
        let auth_factory = AuthTokenFactory::new(jwt_secret.clone());
        Self {
            jwt_secret,
            auth_factory,
        }
    }

    /// Creates a fresh instance of the Axum app router for testing.
    pub fn create_router(&self) -> axum::Router {
        let pool = sqlx::postgres::PgPoolOptions::new()
            .connect_lazy("postgres://postgres:postgres@localhost:5432/test_db")
            .expect("Lazy pool creation should succeed");

        let state = AppState {
            db: pool,
            jwt_secret: self.jwt_secret.clone(),
        };

        create_app(state)
    }

    /// Build an authenticated request using token generated by `AuthTokenFactory`.
    pub fn authenticated_request(
        &self,
        method: http::Method,
        uri: &str,
        user_id: &str,
        body: Option<Value>,
    ) -> Request<Body> {
        let bearer = self.auth_factory.bearer_header(user_id);
        let req = Request::builder()
            .method(method)
            .uri(uri)
            .header(http::header::AUTHORIZATION, bearer)
            .header(http::header::CONTENT_TYPE, "application/json");

        if let Some(json_body) = body {
            req.body(Body::from(json_body.to_string())).unwrap()
        } else {
            req.body(Body::empty()).unwrap()
        }
    }

    /// Build an unauthenticated request without Authorization header.
    pub fn unauthenticated_request(
        &self,
        method: http::Method,
        uri: &str,
        body: Option<Value>,
    ) -> Request<Body> {
        let req = Request::builder()
            .method(method)
            .uri(uri)
            .header(http::header::CONTENT_TYPE, "application/json");

        if let Some(json_body) = body {
            req.body(Body::from(json_body.to_string())).unwrap()
        } else {
            req.body(Body::empty()).unwrap()
        }
    }
}

// Helper to parse response body to JSON
async fn response_to_json(response: axum::response::Response) -> Value {
    let bytes = response.into_body().collect().await.unwrap().to_bytes();
    serde_json::from_slice(&bytes).unwrap_or(json!({}))
}

#[tokio::test]
async fn test_get_health_routes() {
    let factory = TestAppFactory::new();
    let app = factory.create_router();

    let req = Request::builder()
        .method("GET")
        .uri("/health")
        .body(Body::empty())
        .unwrap();

    let response = app.oneshot(req).await.unwrap();
    assert_eq!(response.status(), StatusCode::OK);

    let json_res = response_to_json(response).await;
    assert_eq!(json_res, json!({ "status": "ok" }));
}

#[tokio::test]
async fn test_get_openapi_json_basic_auth() {
    let factory = TestAppFactory::new();
    
    // Case 1: Without Basic Auth -> 401 Unauthorized with WWW-Authenticate header
    {
        let app = factory.create_router();
        let req = Request::builder()
            .method("GET")
            .uri("/openapi.json")
            .body(Body::empty())
            .unwrap();
        let response = app.oneshot(req).await.unwrap();
        assert_eq!(response.status(), StatusCode::UNAUTHORIZED);
        assert!(response.headers().contains_key("www-authenticate"));
    }

    // Case 2: With valid Basic Auth -> 200 OK
    {
        let app = factory.create_router();
        let req = Request::builder()
            .method("GET")
            .uri("/openapi.json")
            .header(http::header::AUTHORIZATION, "Basic YWRtaW46YWRtaW4=") // admin:admin
            .body(Body::empty())
            .unwrap();
        let response = app.oneshot(req).await.unwrap();
        assert_eq!(response.status(), StatusCode::OK);

        let json_res = response_to_json(response).await;
        assert!(json_res.get("openapi").is_some());
        assert_eq!(json_res["info"]["title"], "LAPES - API");
    }
}

